//compound assignment operator
let count = 100;

count += 5;
console.log(count); // Output: 105   
count *= 5;
console.log(count); // Output: 525   
count /= 5;
console.log(count); // Output: 15   
count -= 5;
console.log(count); // Output: 10   
count %= 5;
console.log(count); // Output: 0   